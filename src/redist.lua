-----------------------------------------------------------------
-- General redis-lua utilities.
-----------------------------------------------------------------
local config = require( 'config' )
local redis = require( 'redis' )

-----------------------------------------------------------------
-- Aliases.
-----------------------------------------------------------------
local HOST = assert( config.HOST )
local PORT = assert( config.PORT )

-----------------------------------------------------------------
-- Methods.
-----------------------------------------------------------------
local function connect()
  return assert( redis.connect( HOST, PORT ) )
end

-----------------------------------------------------------------
-- Module.
-----------------------------------------------------------------
return {
  connect=connect, --
}
